#!/usr/bin/env node
/**
 * Extracts the Levant coastline from Natural Earth (public domain, via
 * world-atlas) and emits it as SVG path data already projected into the map's
 * viewBox.
 *
 * Runs at build time so the site ships no mapping library and no runtime
 * topojson parsing — just a string.
 *
 * Natural Earth is public domain. It is modern physical geography (where the
 * land meets the sea), NOT a political basemap and NOT the disputed Mandate
 * survey rasters, whose rights are still unresolved. See
 * cultural-research/dossier-003-maps-and-provenance.md.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { feature } from "topojson-client";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const VIEW = { w: 760, h: 1260 };
const BBOX = { minLat: 31.2, maxLat: 33.3, minLon: 34.2, maxLon: 35.7 };
const PAD = { x: 40, y: 40 };

const meanLat = (BBOX.minLat + BBOX.maxLat) / 2;
const lonScale = Math.cos((meanLat * Math.PI) / 180);
const spanLat = BBOX.maxLat - BBOX.minLat;
const spanLon = (BBOX.maxLon - BBOX.minLon) * lonScale;
const scale = Math.min((VIEW.w - PAD.x * 2) / spanLon, (VIEW.h - PAD.y * 2) / spanLat);
const cx = (BBOX.minLon + BBOX.maxLon) / 2;
const cy = (BBOX.minLat + BBOX.maxLat) / 2;

const project = (lon, lat) => [
  VIEW.w / 2 + (lon - cx) * lonScale * scale,
  VIEW.h / 2 - (lat - cy) * scale,
];

// Generous margin so segments do not stop exactly at the frame edge.
const M = 0.6;
const inside = ([lon, lat]) =>
  lon >= BBOX.minLon - M &&
  lon <= BBOX.maxLon + M &&
  lat >= BBOX.minLat - M &&
  lat <= BBOX.maxLat + M;

const topo = JSON.parse(
  readFileSync(join(root, "node_modules", "world-atlas", "land-10m.json"), "utf8"),
);
const land = feature(topo, topo.objects.land);

const rings = [];
const collect = (geom) => {
  if (geom.type === "Polygon") rings.push(...geom.coordinates);
  else if (geom.type === "MultiPolygon")
    for (const poly of geom.coordinates) rings.push(...poly);
};
if (land.type === "FeatureCollection") for (const f of land.features) collect(f.geometry);
else collect(land.geometry);

// Keep contiguous runs of in-frame points; each run becomes one open subpath.
const paths = [];
let kept = 0;
for (const ring of rings) {
  let run = [];
  for (const pt of ring) {
    if (inside(pt)) run.push(pt);
    else {
      if (run.length > 1) paths.push(run);
      run = [];
    }
  }
  if (run.length > 1) paths.push(run);
}

const d = paths
  .map((run) => {
    kept += run.length;
    return run
      .map(([lon, lat], i) => {
        const [x, y] = project(lon, lat);
        return `${i === 0 ? "M" : "L"}${x.toFixed(1)},${y.toFixed(1)}`;
      })
      .join("");
  })
  .join(" ");

// The selvedge: for each weft row, where the cloth begins.
// A coastline is the land's finished self-edge, which is what a selvedge is in
// weaving. Sampling it per row lets the loom weave a piece shaped like the land.
const ROWS = 150;
const selvedge = [];
for (let r = 0; r < ROWS; r++) {
  const y = (VIEW.h / (ROWS - 1)) * r;
  // Westernmost coastline point near this row, if the coast passes through it.
  let best = null;
  for (const run of paths) {
    for (const [lon, lat] of run) {
      const [px, py] = project(lon, lat);
      if (Math.abs(py - y) <= VIEW.h / (ROWS - 1)) {
        if (best === null || px < best) best = px;
      }
    }
  }
  selvedge.push(best === null ? null : Number(best.toFixed(1)));
}

// A selvedge is continuous. Rows the coast does not cross take their edge from
// the nearest row that does, so the cloth has one unbroken edge instead of
// stray full-width threads.
for (let r = 0; r < selvedge.length; r++) {
  if (selvedge[r] !== null) continue;
  let back = r;
  let fwd = r;
  while (back >= 0 && selvedge[back] === null) back--;
  while (fwd < selvedge.length && selvedge[fwd] === null) fwd++;
  const b = back >= 0 ? selvedge[back] : null;
  const f = fwd < selvedge.length ? selvedge[fwd] : null;
  selvedge[r] = b !== null && f !== null ? (b + f) / 2 : (b ?? f ?? 0);
}

const out = `// GENERATED by scripts/build-coastline.mjs — do not edit.
//
// Coastline of the frame, from Natural Earth 1:10m land polygons via
// world-atlas. Natural Earth is public domain. This is modern physical
// geography, not a political basemap and not the Mandate survey rasters.
//
// ${paths.length} segments, ${kept} points, projected into a ${VIEW.w}x${VIEW.h} viewBox.

export const COASTLINE_PATH =
  "${d}";

/**
 * Where the cloth starts on each of ${ROWS} weft rows, top to bottom.
 * Continuous: rows the coast does not cross inherit from their neighbours.
 */
export const SELVEDGE: number[] = ${JSON.stringify(selvedge)};

export const VIEW_W = ${VIEW.w};
export const VIEW_H = ${VIEW.h};

export const COASTLINE_SOURCE =
  "Natural Earth 1:10m land polygons (public domain), via world-atlas";
`;

writeFileSync(join(root, "src", "content", "coastline.ts"), out);
console.log(
  `coastline: ${paths.length} segments, ${kept} points, ${(d.length / 1024).toFixed(1)}KB path data`,
);
